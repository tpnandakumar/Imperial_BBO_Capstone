def decimal_differences(values):
    levels = [values]
    while len(levels[-1]) > 1:
        prior = levels[-1]
        levels.append([prior[i+1] - prior[i] for i in range(len(prior)-1)])
    return levels

def main():
    out = Path("week_11_engine_outputs")
    out.mkdir(exist_ok=True)

    rows = []
    for f in range(8):
        vals = [Decimal(row[f]) for row in OUTPUT_STRINGS]
        best_i = max(range(10), key=lambda i: vals[i])
        deltas = decimal_differences(vals)
        recent = deltas[1][-1]
        recent_second = deltas[2][-1]
        sign_changes = sum(
            1 for a,b in zip(deltas[1][:-1], deltas[1][1:])
            if a != 0 and b != 0 and (a > 0) != (b > 0)
        )
        rows.append({
            "Function": f"Function {f+1}",
            "Best_Week": best_i + 1,
            "Best_Output_Exact": str(vals[best_i]),
            "Best_Input": "-".join(f"{x:.6f}" for x in INPUTS[best_i][f]),
            "Week_10_Output_Exact": str(vals[-1]),
            "Latest_Delta_Exact": str(recent),
            "Latest_Second_Delta_Exact": str(recent_second),
            "Delta_Sign_Changes": sign_changes,
            "Week_11_Strategy": STRATEGIES[f],
            "Week_11_Input": "-".join(f"{x:.6f}" for x in WEEK11[f])
        })

    with (out / "week_11_engine_analysis.csv").open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=rows[0].keys())
        writer.writeheader()
        writer.writerows(rows)

